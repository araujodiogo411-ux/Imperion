const normStr = (s: string) =>
  s
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .trim();

export function resolveStateMetadata(
  countryOriginalName: string,
  rawName: string
): { name: string; capital: string } {
  const translated = STATE_NAME_TRANSLATIONS[rawName] || rawName;
  const defs = REAL_COUNTRY_STATES[countryOriginalName];
  if (defs) {
    const nTarget = normStr(translated);
    const nRaw = normStr(rawName);
    const exact = defs.find(
      (d) => normStr(d.name) === nTarget || normStr(d.name) === nRaw
    );
    if (exact) return { name: exact.name, capital: exact.capital };
    const partial = defs.find(
      (d) => normStr(d.name).includes(nTarget) || nTarget.includes(normStr(d.name))
    );
    if (partial) return { name: translated, capital: partial.capital };
  }
  return { name: translated, capital: translated };
}
